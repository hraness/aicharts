function provenance(key: keyof typeof sources): BenchmarkAtlasDataset["source"] {
  const checked = snapshot[key].source;
  return { name: sources[key].name, url: sources[key].url, retrievedAt: checked.retrievedAt, revision: `sha256:${checked.sha256}` };
}
function point(key: keyof typeof sources, row: { id: string; label: string; provider: string; score: number }): BenchmarkAtlasPoint {
  return { id: row.id, label: row.label, model: row.label, provider: row.provider, harness: null, effort: null, score: row.score, costUsd: null, uncertainty: null, sourceUrl: sources[key].url };
}
const detail = (label: string, value: string | number) => ({ label, value: String(value) });

